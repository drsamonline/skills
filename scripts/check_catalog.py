#!/usr/bin/env python3
"""Fail if a skill folder is not in the catalogue.

catalog.json is generated by the refresh job, which is deliberately guarded to
run on a schedule or by hand. That means a skill added today is invisible to
the catalogue — and to anything that reads it — until the next refresh, up to a
week later. That is exactly what happened: `doc-claims-guard` sat in the
repository and was absent from the catalogue for days, and nothing said so.

This is the check that says so. It does not regenerate anything; it compares
the folders on disk against the ids in the catalogue and names what is missing.
"""
import json
import os
import sys


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    skills_dir = os.path.join(root, "skills")
    catalog_path = os.path.join(root, "catalog.json")

    if not os.path.isdir(skills_dir) or not os.path.isfile(catalog_path):
        print("skills/ or catalog.json is missing", file=sys.stderr)
        return 1

    folders = {
        name
        for name in os.listdir(skills_dir)
        if os.path.isfile(os.path.join(skills_dir, name, "meta.json"))
    }

    with open(catalog_path, encoding="utf-8") as handle:
        catalog = json.load(handle)
    listed = {entry.get("id") for entry in catalog.get("skills", [])}

    missing = sorted(folders - listed)
    orphaned = sorted(listed - folders)

    if missing or orphaned:
        if missing:
            print("skills on disk that the catalogue does not list:")
            for name in missing:
                print(f"  {name}")
        if orphaned:
            print("catalogue entries with no skill folder:")
            for name in orphaned:
                print(f"  {name}")
        print(
            "\nRun the refresh workflow (or regenerate catalog.json the way it does) "
            "and commit the result.",
            file=sys.stderr,
        )
        return 1

    print(f"catalogue lists every skill: {len(folders)} folders, {len(listed)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
